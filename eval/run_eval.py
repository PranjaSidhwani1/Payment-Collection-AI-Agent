"""Automated evaluation harness.

Runs every case in eval/cases.py against the REAL Agent (real Groq
extraction + real lookup-account/process-payment API calls), then reports:
  - pass/fail per case (and per individual check within a case)
  - tool-call correctness (right endpoints, right order, per case)
  - a PII-leak scan across every agent reply
  - aggregate metrics: case pass rate, check pass rate, avg turns/case

Also writes eval/sample_conversations.md - the full transcripts of every
case, which doubles as the "Sample Conversations" deliverable (successful
payment, verification failure, payment failure, and a messy-NLU edge case
are all included).

Usage:
    python -m eval.run_eval
"""
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from dotenv import load_dotenv

load_dotenv()

import api_client  # noqa: E402
from agent import Agent  # noqa: E402
from eval.cases import CASES  # noqa: E402


def run_case(case):
    api_client.call_log.clear()
    bot = Agent()
    transcript = []
    for turn in case.turns:
        reply = bot.next(turn)["message"]
        transcript.append((turn, reply))

    observed_endpoints = [c["endpoint"] for c in api_client.call_log]
    checks = []

    if case.expected_outcome is not None:
        checks.append(
            (
                f"outcome == {case.expected_outcome!r} (got {bot.state.outcome!r})",
                bot.state.outcome == case.expected_outcome,
            )
        )

    checks.append(
        (
            f"tool calls == {case.expected_endpoints} (got {observed_endpoints})",
            observed_endpoints == case.expected_endpoints,
        )
    )

    for check_fn in case.extra_checks:
        checks.append(check_fn(bot, transcript))

    return bot, transcript, checks, list(api_client.call_log)


def format_transcript(case, transcript, call_log):
    lines = [f"## {case.name}", "", case.description, ""]
    for user_msg, agent_msg in transcript:
        lines.append(f"**User:** {user_msg}")
        lines.append("")
        lines.append(f"**Agent:** {agent_msg}")
        lines.append("")
    if call_log:
        lines.append("_API calls made:_")
        for c in call_log:
            lines.append(f"- `{c['endpoint']}` {c['payload']}")
        lines.append("")
    return "\n".join(lines)


def main():
    total_checks = 0
    passed_checks = 0
    passed_cases = 0
    total_turns = 0
    report_sections = []

    print("=" * 78)
    print("PAYMENT COLLECTION AGENT - EVALUATION RUN")
    print("=" * 78)

    for case in CASES:
        start = time.time()
        try:
            bot, transcript, checks, call_log = run_case(case)
        except Exception as exc:  # noqa: BLE001 - surface any crash as a failed case
            print(f"\n[CRASH] {case.name}: {exc!r}")
            report_sections.append(f"## {case.name}\n\nCRASHED: {exc!r}\n")
            total_checks += 1
            continue
        elapsed = time.time() - start

        total_turns += len(case.turns)
        case_passed = all(ok for _, ok in checks)
        passed_cases += int(case_passed)

        status = "PASS" if case_passed else "FAIL"
        print(f"\n[{status}] {case.name}  ({len(case.turns)} turns, {elapsed:.1f}s)")
        print(f"        {case.description}")
        for label, ok in checks:
            total_checks += 1
            passed_checks += int(ok)
            mark = "OK  " if ok else "FAIL"
            print(f"        [{mark}] {label}")

        report_sections.append(format_transcript(case, transcript, call_log))

    print("\n" + "=" * 78)
    print("METRICS")
    print("=" * 78)
    n_cases = len(CASES)
    print(f"Cases:        {passed_cases}/{n_cases} passed ({passed_cases / n_cases:.0%})")
    print(f"Checks:       {passed_checks}/{total_checks} passed ({passed_checks / total_checks:.0%})")
    print(f"Avg turns:    {total_turns / n_cases:.1f} per case")

    out_path = os.path.join(os.path.dirname(__file__), "sample_conversations.md")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("# Sample Conversations (generated by eval/run_eval.py)\n\n")
        f.write(f"Cases passed: {passed_cases}/{n_cases}. Checks passed: {passed_checks}/{total_checks}.\n\n")
        f.write("\n---\n\n".join(report_sections))
    print(f"\nFull transcripts written to {out_path}")

    return 0 if passed_cases == n_cases else 1


if __name__ == "__main__":
    sys.exit(main())
